import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

const credentials = fs.readFileSync(path.resolve('../.tools/acceso-local.txt'), 'utf8');
const email = credentials.match(/Usuario: (.+)/)![1].trim();
const password = credentials.match(/Contraseña: (.+)/)![1].trim();

test('sesión, catálogo, compra, recepción, factura, cobro y despacho', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Correo electrónico').fill(email);
  await page.getByLabel('Contraseña', { exact: false }).fill(password);
  await page.getByRole('button', { name: 'Iniciar sesión' }).click();
  await expect(page.getByRole('heading', { name: 'Vista general' })).toBeVisible();
  const csrf = await page.request.get('/api/v1/csrf').then(r => r.json());
  const headers = { 'X-CSRF-TOKEN': csrf.token, Accept: 'application/json' };
  const sku = `E2E-${Date.now()}`;
  const productResponse = await page.request.post('/api/v1/catalog/items', { headers, data: { sku, name: 'Producto prueba navegador', unit_id: 1, purchase_price: '10.00', sale_price: '20.00', min_stock: '0', active: true } });
  expect(productResponse.ok()).toBeTruthy();
  const item = await productResponse.json();
  await page.getByRole('button', { name: 'Compras', exact: true }).click();
  await page.getByRole('button', { name: '+ Nueva compra' }).click();
  const modal = page.getByRole('dialog');
  await modal.getByLabel('Proveedor').selectOption('1');
  await modal.getByLabel('Almacén').selectOption('1');
  await modal.getByLabel('Producto', { exact: false }).selectOption(String(item.id));
  await modal.getByLabel('Cantidad', { exact: false }).fill('10');
  await modal.getByLabel('Precio', { exact: false }).fill('10');
  await modal.getByRole('button', { name: 'Confirmar documento' }).click();
  await expect(modal.getByRole('button', { name: 'Recibir mercadería', exact: true })).toBeVisible();
  await modal.getByRole('button', { name: 'Recibir mercadería', exact: true }).click();
  await modal.getByLabel('Producto prueba navegador · Cantidad a procesar').fill('4');
  await modal.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(modal.getByRole('heading', { name: 'Documentos relacionados' })).toBeVisible();
  await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Pedidos', exact: true }).click();
  await page.getByRole('button', { name: '+ Nuevo pedido' }).click();
  await modal.getByLabel('Cliente', { exact: true }).selectOption('1');
  await modal.getByLabel('Almacén').selectOption('1');
  await modal.getByLabel('Producto', { exact: false }).selectOption(String(item.id));
  await modal.getByLabel('Cantidad', { exact: false }).fill('4');
  await modal.getByLabel('Precio', { exact: false }).fill('20');
  await modal.getByRole('button', { name: 'Confirmar documento' }).click();
  await modal.getByRole('button', { name: 'Facturar', exact: true }).click();
  await modal.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(modal.getByRole('heading', { name: 'Documentos relacionados' })).toBeVisible();
  await modal.getByRole('button', { name: 'Preparar despacho', exact: true }).click();
  await modal.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(modal.locator('table').last().locator('tbody tr')).toHaveCount(2);
  await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Facturas internas', exact: true }).click();
  await page.getByRole('button', { name: 'Ver detalle' }).first().click();
  await modal.getByRole('button', { name: 'Registrar cobro', exact: true }).click();
  await modal.getByLabel('Medio de pago').selectOption('1');
  await modal.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(modal.getByRole('heading', { name: 'Cobros', exact: true })).toBeVisible();
  await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('button', { name: 'Vista general', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tu operación, en un solo lugar' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Últimos documentos' })).toBeVisible();
  await page.screenshot({ path: '../documentation/auditoria-modernizacion/dashboard-local.png', fullPage: true });
  expect(errors).toEqual([]);
});

